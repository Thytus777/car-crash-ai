"""Image preprocessing service.

Validates, resizes, stores, and quality-checks uploaded images.
"""

import json
import re
import statistics
import uuid
from io import BytesIO
from pathlib import Path

from PIL import Image, ImageFilter, ImageStat

from app.core.config import settings
from app.core.errors import (
    InvalidInputError,
    NotFoundError,
    PayloadTooLargeError,
    UnsupportedMediaTypeError,
)
from app.models.damage import AngleGuidance, ImageQualityWarning

# Quality thresholds
_BLUR_THRESHOLD = 80.0  # Laplacian variance below this → blurry
_DARK_THRESHOLD = 50.0  # Mean brightness below this (0–255) → too dark
_OVEREXPOSED_THRESHOLD = 220.0  # Mean brightness above this → overexposed

# Angle labels we ask users to provide (order matters for guidance message)
EXPECTED_ANGLES = ["front", "rear", "driver side", "passenger side"]

# Decided from the file bytes, never the client-supplied Content-Type.
ALLOWED_FORMATS = {"JPEG", "PNG", "WEBP"}
TARGET_SIZE = (1024, 1024)


# upload_ids are generated by process_upload() as uuid4().hex[:12].
UPLOAD_ID_PATTERN = r"^[0-9a-f]{12}$"
_UPLOAD_ID_RE = re.compile(UPLOAD_ID_PATTERN)


class ImageValidationError(InvalidInputError):
    pass


def _upload_path(upload_id: str) -> Path:
    """Resolve an upload's directory, refusing anything outside upload_dir."""
    root = settings.upload_dir.resolve()
    path = (root / upload_id).resolve()
    if not _UPLOAD_ID_RE.fullmatch(upload_id) or path.parent != root:
        raise InvalidInputError(f"Invalid upload_id: {upload_id!r}")
    return path


class ProcessedImage:
    def __init__(
        self,
        image_id: str,
        original_filename: str,
        saved_path: Path,
        width: int,
        height: int,
        file_size_bytes: int,
    ) -> None:
        self.image_id = image_id
        self.original_filename = original_filename
        self.saved_path = saved_path
        self.width = width
        self.height = height
        self.file_size_bytes = file_size_bytes


_MB = 1024 * 1024


def check_image_count(count: int) -> None:
    if count > settings.max_images_per_request:
        raise PayloadTooLargeError(
            f"Too many images: {count}, max is {settings.max_images_per_request}"
        )


def check_file_size(filename: str, size: int) -> None:
    if size > settings.max_upload_size_mb * _MB:
        raise PayloadTooLargeError(
            f"{filename}: {size / _MB:.1f} MB exceeds the "
            f"{settings.max_upload_size_mb:g} MB per-file limit"
        )


def check_total_size(size: int) -> None:
    if size > settings.max_upload_total_mb * _MB:
        raise PayloadTooLargeError(
            f"Upload total of {size / _MB:.1f} MB exceeds the "
            f"{settings.max_upload_total_mb:g} MB limit"
        )


def _validate_image(data: bytes, filename: str) -> Image.Image:
    check_file_size(filename, len(data))

    try:
        img = Image.open(BytesIO(data))
        img.verify()
        img = Image.open(BytesIO(data))
    except Exception as exc:
        raise ImageValidationError(f"{filename}: not a valid image file") from exc

    if img.format not in ALLOWED_FORMATS:
        raise UnsupportedMediaTypeError(
            f"{filename}: {img.format} images aren't supported; "
            "upload JPEG, PNG or WebP"
        )

    width, height = img.size
    if width < settings.min_image_width or height < settings.min_image_height:
        raise ImageValidationError(
            f"{filename}: resolution {width}x{height} is below "
            f"minimum {settings.min_image_width}x{settings.min_image_height}"
        )

    return img


def _resize_image(img: Image.Image) -> Image.Image:
    img.thumbnail(TARGET_SIZE, Image.Resampling.LANCZOS)
    return img


def _ensure_upload_dir(upload_id: str) -> Path:
    upload_dir = _upload_path(upload_id)
    upload_dir.mkdir(parents=True, exist_ok=True)
    return upload_dir


async def process_upload(
    files: list[tuple[str, bytes, str]],
) -> tuple[str, list[ProcessedImage], list[ImageQualityWarning]]:
    """Process uploaded image files.

    Args:
        files: list of (filename, file_bytes, content_type) tuples.

    Returns:
        (upload_id, list of ProcessedImage, list of ImageQualityWarning).
    """
    check_image_count(len(files))
    check_total_size(sum(len(data) for _, data, _ in files))

    if not files:
        raise ImageValidationError("No images provided")

    upload_id = uuid.uuid4().hex[:12]
    upload_dir = _ensure_upload_dir(upload_id)
    results: list[ProcessedImage] = []
    all_warnings: list[ImageQualityWarning] = []

    for filename, data, _content_type in files:
        img = _validate_image(data, filename)
        all_warnings.extend(check_image_quality(img, filename))

        if img.mode == "RGBA":
            img = img.convert("RGB")

        img = _resize_image(img)

        image_id = uuid.uuid4().hex[:8]
        save_name = f"{image_id}.jpg"
        save_path = upload_dir / save_name
        img.save(save_path, format="JPEG", quality=90)

        results.append(
            ProcessedImage(
                image_id=image_id,
                original_filename=filename,
                saved_path=save_path,
                width=img.size[0],
                height=img.size[1],
                file_size_bytes=save_path.stat().st_size,
            )
        )

    (upload_dir / _QUALITY_FILE).write_text(
        json.dumps([w.model_dump() for w in all_warnings])
    )
    return upload_id, results, all_warnings


def check_image_quality(
    img: Image.Image,
    filename: str,
) -> list[ImageQualityWarning]:
    """Return quality warnings for a single image (blur, brightness)."""
    warnings: list[ImageQualityWarning] = []
    rgb = img.convert("RGB")

    # Blur detection: compute variance of the Laplacian approximation via PIL.
    # High variance = sharp; low variance = blurry.
    gray = rgb.convert("L")
    edges = gray.filter(ImageFilter.FIND_EDGES)
    stat = ImageStat.Stat(edges)
    blur_score = stat.var[0]  # variance of edge magnitudes

    if blur_score < _BLUR_THRESHOLD:
        warnings.append(
            ImageQualityWarning(
                image_filename=filename,
                warning_type="blurry",
                message=(
                    f"{filename} appears blurry (score {blur_score:.0f}). "
                    "Retake with the camera steady and subject in focus."
                ),
            )
        )

    # Brightness detection
    stat_rgb = ImageStat.Stat(rgb)
    mean_brightness = statistics.mean(stat_rgb.mean[:3])

    if mean_brightness < _DARK_THRESHOLD:
        warnings.append(
            ImageQualityWarning(
                image_filename=filename,
                warning_type="dark",
                message=(
                    f"{filename} is too dark (brightness {mean_brightness:.0f}/255). "
                    "Ensure good lighting or retake outdoors in daylight."
                ),
            )
        )
    elif mean_brightness > _OVEREXPOSED_THRESHOLD:
        warnings.append(
            ImageQualityWarning(
                image_filename=filename,
                warning_type="overexposed",
                message=(
                    f"{filename} is overexposed "
                    f"(brightness {mean_brightness:.0f}/255). "
                    "Avoid direct sunlight on the lens or shade the vehicle."
                ),
            )
        )

    return warnings


def assess_angle_coverage(image_count: int) -> AngleGuidance:
    """Suggest more photos when there are fewer than the four standard views.

    Which angles were actually photographed isn't detected (that needs a
    per-image classifier), so this never reports detected or missing angles.
    """
    if image_count >= len(EXPECTED_ANGLES):
        return AngleGuidance()
    return AngleGuidance(
        suggestion=(
            f"Only {image_count} photo(s) uploaded. Upload at least 4 photos "
            f"({', '.join(EXPECTED_ANGLES)}) for the most accurate assessment."
        )
    )


_QUALITY_FILE = "quality.json"


def load_quality_warnings(upload_id: str) -> list[ImageQualityWarning]:
    """Quality warnings computed at upload time (empty if none were saved)."""
    path = _upload_path(upload_id) / _QUALITY_FILE
    if not path.is_file():
        return []
    return [ImageQualityWarning.model_validate(w) for w in json.loads(path.read_text())]


def load_images(upload_id: str) -> list[bytes]:
    """Load all processed (JPEG) images for an upload, in a stable order."""
    upload_dir = _upload_path(upload_id)
    if not upload_dir.exists():
        raise NotFoundError(f"Upload {upload_id} not found")

    return [path.read_bytes() for path in sorted(upload_dir.glob("*.jpg"))]
